import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { cube2x2x2 } from "../vendor/cubing/puzzles/index.js";

const MOVE_NAMES = Object.freeze([
  "U", "U2", "U'",
  "F", "F2", "F'",
  "R", "R2", "R'",
]);

function asArray(value, label) {
  if (!value || typeof value.length !== "number") {
    throw new Error(`TWO_BY_TWO_${label}_MISSING`);
  }
  return Array.from(value, (entry) => Number(entry));
}

function assertPermutation(values, label) {
  if (values.length !== 8) {
    throw new Error(`TWO_BY_TWO_${label}_LENGTH`);
  }
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.some((value, index) => value !== index)) {
    throw new Error(`TWO_BY_TWO_${label}_INVALID_PERMUTATION`);
  }
}

function assertOrientations(values, label) {
  if (
    values.length !== 8
    || values.some((value) => !Number.isInteger(value) || value < 0 || value >= 3)
  ) {
    throw new Error(`TWO_BY_TWO_${label}_INVALID_ORIENTATION`);
  }
}

function compose(left, right) {
  const permutation = new Array(8);
  const orientation = new Array(8);
  for (let newPosition = 0; newPosition < 8; newPosition += 1) {
    const intermediatePosition = right.permutation[newPosition];
    permutation[newPosition] = left.permutation[intermediatePosition];
    orientation[newPosition] = (
      left.orientation[intermediatePosition] + right.orientation[newPosition]
    ) % 3;
  }
  return { permutation, orientation };
}

function identity() {
  return {
    permutation: Array.from({ length: 8 }, (_, index) => index),
    orientation: Array(8).fill(0),
  };
}

function power(transform, exponent) {
  let result = identity();
  for (let index = 0; index < exponent; index += 1) {
    result = compose(result, transform);
  }
  return result;
}

function assertIdentity(transform, label) {
  const expected = identity();
  if (
    transform.permutation.some((value, index) => value !== expected.permutation[index])
    || transform.orientation.some((value, index) => value !== 0)
  ) {
    throw new Error(`TWO_BY_TWO_${label}_NOT_IDENTITY`);
  }
}

function rustRows(rows, type) {
  return rows
    .map((row) => `    [${row.map((value) => `${value}${type}`).join(", ")}],`)
    .join("\n");
}

async function main() {
  const loader = typeof cube2x2x2 === "function" ? await cube2x2x2() : cube2x2x2;
  const kpuzzle = await loader.kpuzzle();
  const solved = kpuzzle.defaultPattern();

  const transforms = MOVE_NAMES.map((moveName) => {
    const corners = solved.applyAlg(moveName).patternData.CORNERS;
    const permutation = asArray(corners.pieces, `${moveName}_PIECES`);
    const orientation = asArray(corners.orientation, `${moveName}_ORIENTATION`);
    assertPermutation(permutation, `${moveName}_PIECES`);
    assertOrientations(orientation, `${moveName}_ORIENTATION`);
    return { moveName, permutation, orientation };
  });

  for (let face = 0; face < 3; face += 1) {
    const quarter = transforms[face * 3];
    const half = transforms[face * 3 + 1];
    const inverse = transforms[face * 3 + 2];
    assertIdentity(power(quarter, 4), `${quarter.moveName}_ORDER4`);
    assertIdentity(power(half, 2), `${half.moveName}_ORDER2`);
    assertIdentity(compose(quarter, inverse), `${quarter.moveName}_INVERSE`);
  }

  const output = `// Generated by tools/export-2x2-rust-moves.mjs. Do not edit manually.
// Source of truth: the vendored cubing.js cube2x2x2 KPuzzle definition.

pub const MOVE_PERM_MAP: [[usize; 8]; 9] = [
${rustRows(transforms.map((entry) => entry.permutation), "usize")}
];

pub const MOVE_ORI_DELTA: [[u8; 8]; 9] = [
${rustRows(transforms.map((entry) => entry.orientation), "u8")}
];
`;

  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const outputPath = path.resolve(scriptDir, "../solver-wasm/src/generated_2x2_moves.rs");
  await fs.writeFile(outputPath, output, "utf8");
  console.log(`Wrote ${outputPath}`);
}

main().catch((error) => {
  console.error(error?.stack || error);
  process.exitCode = 1;
});
