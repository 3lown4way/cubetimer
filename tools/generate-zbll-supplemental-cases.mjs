import fs from "node:fs";
import { KPattern } from "../vendor/cubing/kpuzzle/index.js";
import { cube3x3x3 } from "../vendor/cubing/puzzles/index.js";
import { experimentalSolve3x3x3IgnoringCenters } from "../vendor/cubing/search/index.js";
import { buildZbllCaseIndexData } from "../solver/cfop3x3.js";

const kpuzzle = await cube3x3x3.kpuzzle();
const solved = kpuzzle.defaultPattern();
const baseLibrary = await buildZbllCaseIndexData();

function permutations(values) {
  const out = [];
  const used = new Array(values.length).fill(false);
  const path = [];
  function visit() {
    if (path.length === values.length) {
      out.push(path.slice());
      return;
    }
    for (let index = 0; index < values.length; index += 1) {
      if (used[index]) continue;
      used[index] = true;
      path.push(values[index]);
      visit();
      path.pop();
      used[index] = false;
    }
  }
  visit();
  return out;
}

function permutationParity(values) {
  let parity = 0;
  for (let i = 0; i < values.length; i += 1) {
    for (let j = i + 1; j < values.length; j += 1) {
      if (values[i] > values[j]) parity ^= 1;
    }
  }
  return parity;
}

function orbitKey(orbit, positions) {
  const parts = [];
  for (const position of positions) {
    parts.push(`p${orbit.pieces[position]}`, `o${orbit.orientation[position]}`);
  }
  return parts.join(",");
}

function zbllKey(data) {
  return `ZC:${orbitKey(data.CORNERS, [0, 1, 2, 3])}|ZE:${orbitKey(data.EDGES, [0, 1, 2, 3])}`;
}

function isSolved(pattern) {
  return pattern.experimentalIsSolved({ ignorePuzzleOrientation: false });
}

function applyMoves(pattern, moves) {
  try {
    let next = pattern;
    for (const move of moves) next = next.applyMove(move);
    return next;
  } catch {
    return null;
  }
}

function baseCandidatesForKey(key) {
  const packed = baseLibrary.index?.[key];
  if (!Array.isArray(packed)) return [];
  return packed
    .map((entry) => (Array.isArray(entry?.[2]) ? entry[2] : null))
    .filter((moves) => Array.isArray(moves) && moves.length);
}

const topPermutations = permutations([0, 1, 2, 3]);
const states = new Map();
for (const cornerPermutation of topPermutations) {
  const cornerParity = permutationParity(cornerPermutation);
  for (const edgePermutation of topPermutations) {
    if (permutationParity(edgePermutation) !== cornerParity) continue;
    for (let o0 = 0; o0 < 3; o0 += 1) {
      for (let o1 = 0; o1 < 3; o1 += 1) {
        for (let o2 = 0; o2 < 3; o2 += 1) {
          const o3 = (3 - ((o0 + o1 + o2) % 3)) % 3;
          const data = structuredClone(solved.patternData);
          for (let position = 0; position < 4; position += 1) {
            data.CORNERS.pieces[position] = cornerPermutation[position];
            data.CORNERS.orientation[position] = [o0, o1, o2, o3][position];
            data.EDGES.pieces[position] = edgePermutation[position];
            data.EDGES.orientation[position] = 0;
          }
          const pattern = new KPattern(kpuzzle, data);
          const key = zbllKey(data);
          states.set(key, pattern);
        }
      }
    }
  }
}

const uncovered = [];
let baseCovered = 0;
let invalidIndexedStates = 0;
for (const [key, pattern] of states) {
  if (isSolved(pattern)) continue;
  const candidates = baseCandidatesForKey(key);
  const valid = candidates.some((moves) => {
    const result = applyMoves(pattern, moves);
    return result && isSolved(result);
  });
  if (valid) baseCovered += 1;
  else {
    if (candidates.length) invalidIndexedStates += 1;
    uncovered.push({ key, pattern });
  }
}

const supplemental = [];
for (let index = 0; index < uncovered.length; index += 1) {
  const { key, pattern } = uncovered[index];
  const alg = await experimentalSolve3x3x3IgnoringCenters(pattern);
  const solution = alg?.toString?.().trim() || "";
  if (!solution) throw new Error(`No supplemental solution for ${key}`);
  const result = pattern.applyAlg(solution);
  if (!isSolved(result)) throw new Error(`Invalid supplemental solution for ${key}: ${solution}`);
  const moveCount = solution.split(/\s+/).filter(Boolean).length;
  if (moveCount > 22) {
    throw new Error(`Supplemental ZBLL exceeds 22 moves (${moveCount}) for ${key}: ${solution}`);
  }
  supplemental.push([key, solution]);
  if ((index + 1) % 10 === 0 || index + 1 === uncovered.length) {
    console.log(`[ZBLL supplement] ${index + 1}/${uncovered.length}`);
  }
}

const source = [
  "// Auto-generated by tools/generate-zbll-supplemental-cases.mjs",
  "// Exact-state ZBLL algorithms for legal states absent from the primary dataset.",
  `export const ZBLL_SUPPLEMENTAL_CASES = Object.freeze(${JSON.stringify(supplemental, null, 2)});`,
  "",
].join("\n");
fs.writeFileSync("solver/zbllSupplementalCases.js", source);

const moveCounts = supplemental.map((entry) => entry[1].split(/\s+/).filter(Boolean).length);
const report = {
  legalStates: states.size,
  requiredStates: states.size - 1,
  baseIndexCaseCount: baseLibrary.caseCount,
  baseIndexCandidateCount: baseLibrary.candidateCount,
  baseCovered,
  uncoveredCount: uncovered.length,
  invalidIndexedStates,
  supplementalCount: supplemental.length,
  supplementalMoveCount: {
    min: moveCounts.length ? Math.min(...moveCounts) : 0,
    max: moveCounts.length ? Math.max(...moveCounts) : 0,
    average: moveCounts.length
      ? moveCounts.reduce((sum, value) => sum + value, 0) / moveCounts.length
      : 0,
  },
};
fs.mkdirSync("benchmark-results", { recursive: true });
fs.writeFileSync(
  "benchmark-results/zbll-coverage-audit.json",
  `${JSON.stringify(report, null, 2)}\n`,
);
console.log(JSON.stringify(report, null, 2));
